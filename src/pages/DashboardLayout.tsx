const NAV_ITEMS = [
  { id: "/dashboard", label: "Dashboard", icon: Ic.grid },
  { id: "/dashboard/ventas", label: "Ventas", icon: Ic.cart },
  { id: "/dashboard/productos", label: "Productos", icon: Ic.box },
  { id: "/dashboard/caja", label: "Caja", icon: Ic.cash },
  { id: "/dashboard/configuracion", label: "Configuración", icon: Ic.config },
];

export default function DashboardLayout() {
  const navigate = useNavigate();
  const location = useLocation();

  const handleLogout = () => {
    clearSession();
    window.location.href = "/login";
  };

  // Mostrar título solo en dashboard
  const showHeader = location.pathname === "/dashboard";

  return (
    <div className="db-root">
      <aside className="db-sidebar">
        <div className="db-brand">
          <div className="db-brand-icon">{Ic.pos}</div>
          <div>
            <div className="db-brand-name">SmarTable</div>
            <div className="db-brand-sub">Punto de Venta</div>
          </div>
        </div>


        <nav className="db-nav">
          {NAV_ITEMS.map((item) => (
            <button
              key={item.id}
              className={`db-nav-item ${location.pathname === item.id ? "active" : ""}`}
              onClick={() => navigate(item.id)}
            >
              {item.icon}
              {item.label}
            </button>
          ))}
        </nav>

        <div className="db-user" onClick={handleLogout}>
          <div className="db-user-avatar">A</div>
          <div>
            <div className="db-user-name">Administrador</div>
            <div className="db-user-role">Cerrar sesión</div>
          </div>
          <div className="db-user-chevron">{Ic.logout}</div>
        </div>
      </aside>

      <main className="db-main">
        {showHeader && (
          <div className="db-page-title">Dashboard</div>
        )}
        <Outlet />
      </main>
    </div>
  );
}